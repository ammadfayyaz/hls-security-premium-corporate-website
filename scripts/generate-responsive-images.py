"""Development-only responsive asset preparation. Requires Pillow.
Not required by Netlify builds; originals are never modified.
"""
from pathlib import Path
import json
from PIL import Image

root = Path(__file__).resolve().parents[1]
public = root / 'client/public'
output = public / 'images/responsive'
output.mkdir(parents=True, exist_ok=True)
assets = {
    '/images/products/product-control-panel_0dae52ff.jpg': 'security-alarm-systems',
    '/images/products/product-ptz-camera_3d15e3b3.jpg': 'cctv-systems',
    '/images/products/product-energizer_8348abe5.jpg': 'electric-fence-systems',
    '/images/products/product-smoke-detector_1fb36b49.jpg': 'fire-detection-systems',
    '/images/products/gate-automation.jpg': 'gate-automation-systems',
    '/images/products/home-automation.jpg': 'home-automation-systems',
    '/images/services/monitoring-center.jpg': 'security-monitoring',
    '/images/services/armed-response.jpg': 'security-response',
    '/images/services/cctv-camera.jpg': 'security-site-assessment',
}
variants = {}
for source, name in assets.items():
    with Image.open(public / source.lstrip('/')) as original:
        image = original.convert('RGB')
        candidates = []
        for width in [640, 960]:
            if width >= image.width:
                continue
            height = round(image.height * width / image.width)
            filename = f'{name}-{width}.webp'
            image.resize((width, height), Image.Resampling.LANCZOS).save(output / filename, 'WEBP', quality=88, method=6)
            candidates.append(f'/images/responsive/{filename} {width}w')
            print(filename, width, height, (output / filename).stat().st_size, 'bytes')
        candidates.append(f'{source} {image.width}w')
        variants[source] = ', '.join(candidates)
content = ('// Responsive variants of existing artwork, generated by scripts/generate-responsive-images.py.\n'
           'const variants: Record<string, string> = ' + json.dumps(variants, indent=2) + ';\n\n'
           'export function responsiveImage(src: string, overview = false) {\n'
           '  return { srcSet: variants[src], sizes: overview ? "(min-width: 1024px) 33vw, (min-width: 768px) 50vw, 100vw" : "(min-width: 1024px) 50vw, 100vw" };\n'
           '}\n')
(root / 'client/src/lib/responsiveImages.ts').write_text(content)
